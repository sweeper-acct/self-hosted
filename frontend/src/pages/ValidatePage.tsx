function SortTh({
  col, sortCol, sortDir, onSort, thClass = '', children,
}: {
  col: string; sortCol: string | null; sortDir: 'asc' | 'desc'
  onSort: (col: string) => void; thClass?: string; children: React.ReactNode
}) {
  const active = sortCol === col
  return (
    <th
      onClick={() => onSort(col)}
      className={`cursor-pointer select-none border-b border-gray-200 px-3 py-2 ${thClass}`}
    >
      <span className="inline-flex items-center gap-1">
        {children}
        <span className={`text-[9px] leading-none ${active ? 'text-gray-700' : 'text-gray-300'}`}>
          {active ? (sortDir === 'asc' ? '↑' : '↓') : '↕'}
        </span>
      </span>
    </th>
  )
}

