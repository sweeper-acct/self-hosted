// ── Helpers ───────────────────────────────────────────────────────────────────

function confidenceScore(row: TransactionRow): number {
  return parseFloat(row.confidence_score) || 1.0
}

function isFlagged(row: TransactionRow): boolean {
  return confidenceScore(row) < FLAGGED_CONFIDENCE_THRESHOLD
}

function buildEditList(
  edits: Map<number, Partial<TransactionRow>>,
  rows: TransactionRow[],
): RowEdit[] {
  const list: RowEdit[] = []
  edits.forEach((rowEdits, rowIdx) => {
    const original = rows[rowIdx]
    if (!original) return
    Object.entries(rowEdits).forEach(([field, newValue]) => {
      list.push({
        row_ref: String(rowIdx + 1),
        field,
        old_value: original[field as keyof TransactionRow] ?? '',
        new_value: newValue as string,
      })
    })
  })
  return list
}

function sortedByTaskOrder(tasks: CaseTask[]): CaseTask[] {
  return [...tasks].sort((a, b) => {
    const ai = TASK_ORDER.indexOf(a.task_type)
    const bi = TASK_ORDER.indexOf(b.task_type)
    return (ai === -1 ? 99 : ai) - (bi === -1 ? 99 : bi)
  })
}

// ── Small components ──────────────────────────────────────────────────────────

function StatusDot({
  status,
  isCurrent = false,
  isPrior = false,
}: {
  status: string
  isCurrent?: boolean
  isPrior?: boolean
}) {
  if (isCurrent) {
    return <span className="inline-block h-2 w-2 flex-shrink-0 rounded-full bg-gray-900" />
  }
  // Prior to the active step → always green (it completed, regardless of DB snapshot lag)
  if (isPrior && status !== 'rejected') {
    return <span className="inline-block h-2 w-2 flex-shrink-0 rounded-full bg-green-500" />
  }
  const cls: Record<string, string> = {
    pending:       'border border-gray-300 bg-transparent',
    in_progress:   'bg-blue-400',
    waiting_human: 'bg-amber-400',
    approved:      'bg-green-500',
    validated:     'bg-green-500',
    reviewed:      'bg-green-500',
    confirmed:     'bg-green-500',
    certified:     'bg-green-500',
    complete:      'bg-green-500',
    rejected:      'bg-red-400',
  }
  return (
    <span
      className={`inline-block h-2 w-2 flex-shrink-0 rounded-full ${cls[status] ?? 'border border-gray-300 bg-transparent'}`}
    />
  )
}

