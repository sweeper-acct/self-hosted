interface TaskListProps {
  tasks: CaseTask[]
  currentTaskId: string
  collapsed: boolean
  onToggle: () => void
}

function TaskList({ tasks, currentTaskId, collapsed, onToggle }: TaskListProps) {
  const sorted = sortedByTaskOrder(tasks)
  const currentIndex = sorted.findIndex((t) => t.id === currentTaskId)
  // Which task is actually executing or waiting for a human — drives the dot indicator
  const activeIndex = sorted.findIndex((t) =>
    ['in_progress', 'waiting_human'].includes(t.status),
  )
  // When viewing a rejected task (e.g. after a reject chain), treat it as the
  // pivot so downstream completed steps show as empty circles, not stale green.
  const rejectedViewIndex =
    activeIndex === -1 && currentIndex !== -1 && sorted[currentIndex]?.status === 'rejected'
      ? currentIndex
      : -1
  const pivotIndex = activeIndex !== -1 ? activeIndex : rejectedViewIndex !== -1 ? rejectedViewIndex : currentIndex
  const _DONE = new Set(['complete', 'approved', 'waiting_human', 'validated', 'reviewed', 'confirmed', 'certified'])
  return (
    <div className={`flex flex-col ${collapsed ? 'w-10' : 'w-60'} flex-shrink-0 border-r border-gray-200 bg-white transition-all duration-150`}>
      <div className="flex h-10 flex-shrink-0 items-center justify-between border-b border-gray-200 px-3">
        {!collapsed && (
          <span className="text-xs font-semibold uppercase tracking-wide text-gray-500">
            Folder steps
          </span>
        )}
        <button
          onClick={onToggle}
          className="ml-auto text-gray-400 hover:text-gray-600"
          title={collapsed ? 'Expand' : 'Collapse'}
        >
          {collapsed ? '›' : '‹'}
        </button>
      </div>
      <nav className="flex-1 overflow-y-auto py-2">
        {sorted.map((t, idx) => {
          const isViewing = t.id === currentTaskId
          const isActiveDot = activeIndex !== -1 ? idx === activeIndex : isViewing
          const isPrior = pivotIndex !== -1 && idx < pivotIndex
          const effectiveStatus =
            pivotIndex !== -1 && idx > pivotIndex && _DONE.has(t.status) ? 'pending' : t.status
          return (
            <div
              key={t.id}
              className={`flex items-center gap-2.5 px-3 py-2 ${
                isActiveDot ? 'font-semibold text-gray-900' : 'text-gray-400'
              }`}
            >
              <StatusDot status={effectiveStatus} isCurrent={isActiveDot} isPrior={isPrior} />
              {!collapsed && (
                <span className="truncate text-sm">
                  {TASK_LABELS[t.task_type] ?? t.task_type}
                </span>
              )}
            </div>
          )
        })}
      </nav>
    </div>
  )
}

